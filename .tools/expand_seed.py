def S(
    name_ko: str,
    short_ko: str,
    sym_type: str,
    *,
    unicode: str | None = None,
    latex: str | None = None,
    name_en: str | None = None,
    reading_ko: str | None = None,
    reading_en: str | None = None,
    difficulty: int = 2,
    flags: list[str] | None = None,
    aliases: list[tuple[str, str]] | None = None,
    domains: list[tuple[str, str]] | None = None,
    examples: list[tuple[str, str]] | None = None,
) -> dict:
    e: dict = {
        "canonical_name_ko": name_ko,
        "short_meaning_ko": short_ko,
        "symbol_type": sym_type,
        "difficulty_level": difficulty,
        "flags": flags or [],
        "aliases": [list(a) for a in (aliases or [])],
        "domains": [list(d) for d in (domains or [])],
        "examples": [list(x) for x in (examples or [])],
    }
    if unicode is not None:
        e["unicode_char"] = unicode
    if latex is not None:
        e["latex_command"] = latex
    if name_en is not None:
        e["canonical_name_en"] = name_en
    if reading_ko is not None:
        e["reading_ko"] = reading_ko
    if reading_en is not None:
        e["reading_en"] = reading_en
    return e


